def get_ui_content(lang: str | None = None) -> dict[str, Any]:
    """Return full bilingual UI bundles or a single requested language bundle."""
    if lang in UI_BUNDLES:
        return UI_BUNDLES[lang]
    return UI_BUNDLES


def render_share_card_svg(
    *,
    score: int,
    verdict: str,
    category: str,
    lang: str = "ar",
) -> dict[str, str]:
    """Render a crisp 1080x1080 SVG summary card in Python for PNG export."""
    clean_lang = "en" if lang == "en" else "ar"
    bundle = UI_BUNDLES[clean_lang]
    clean_score = max(0, min(100, int(score)))
    clean_verdict = verdict if verdict in VERDICT_COLORS else "suspicious"
    accent = VERDICT_COLORS[clean_verdict]

    verdict_label = html.escape(str(bundle["result"]["verdicts"][clean_verdict]))
    category_label = html.escape(
        str(bundle["categories"].get(category, bundle["categories"]["other"]))
    )
    app_title = html.escape(f"{bundle['brandAr']} / {bundle['brandEn']}")
    score_label = html.escape(str(bundle["result"]["riskScoreLabel"]))
    cat_heading = html.escape(str(bundle["result"]["categoryLabel"]))
    footer_text = html.escape(str(bundle["result"]["shareFooter"]))
    direction = "rtl" if clean_lang == "ar" else "ltr"

    radius = 155
    circumference = 2 * math.pi * radius
    dash_filled = round((clean_score / 100.0) * circumference, 2)
    dash_gap = round(circumference - dash_filled, 2)
    font = "IBM Plex Sans Arabic, Helvetica Now Display, system-ui, sans-serif"

    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1080" viewBox="0 0 1080 1080">'
        '<rect width="1080" height="1080" fill="#f4f4f2"/>'
        '<rect x="72" y="72" width="936" height="936" rx="32" fill="#ffffff" stroke="rgba(0,0,0,0.1)" stroke-width="2"/>'
        f'<rect x="120" y="120" width="120" height="6" rx="3" fill="{accent}"/>'
        f'<text x="540" y="192" text-anchor="middle" direction="{direction}" '
        f'font-family="{font}" font-size="30" font-weight="500" fill="rgba(0,0,0,0.55)">{app_title}</text>'
        f'<circle cx="540" cy="435" r="{radius}" fill="none" stroke="rgba(0,0,0,0.08)" stroke-width="22"/>'
        + (
            f'<circle cx="540" cy="435" r="{radius}" fill="none" stroke="{accent}" stroke-width="22" '
            f'stroke-linecap="round" stroke-dasharray="{dash_filled} {dash_gap}" transform="rotate(-90 540 435)"/>'
            if clean_score > 0
            else ""
        )
        + f'<text x="540" y="463" text-anchor="middle" font-family="{font}" font-size="104" font-weight="700" fill="#000000">{clean_score}</text>'
        f'<text x="540" y="513" text-anchor="middle" direction="{direction}" '
        f'font-family="{font}" font-size="26" font-weight="500" fill="rgba(0,0,0,0.55)">{score_label}</text>'
        f'<text x="540" y="710" text-anchor="middle" direction="{direction}" '
        f'font-family="{font}" font-size="62" font-weight="700" fill="{accent}">{verdict_label}</text>'
        f'<text x="540" y="785" text-anchor="middle" direction="{direction}" '
        f'font-family="{font}" font-size="32" font-weight="500" fill="rgba(0,0,0,0.78)">{cat_heading}: {category_label}</text>'
        '<line x1="136" y1="888" x2="944" y2="888" stroke="rgba(0,0,0,0.1)" stroke-width="2"/>'
        f'<text x="540" y="950" text-anchor="middle" direction="{direction}" '
        f'font-family="{font}" font-size="24" font-weight="400" fill="rgba(0,0,0,0.55)">{footer_text}</text>'
        "</svg>"
    )
    return {"svg": svg, "filename": f"kashf-verdict-{clean_score}.png"}
